-- PostgreSQL 15. Run as the trusted owner of schema datagateway.
-- Transaction-neutral: the caller owns the transaction and source-view grants.
CREATE SCHEMA IF NOT EXISTS datagateway;
REVOKE ALL ON SCHEMA datagateway FROM PUBLIC;
CREATE TABLE IF NOT EXISTS datagateway.datasource (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(128) NOT NULL CHECK (name COLLATE "C" ~ '^[A-Za-z_][A-Za-z0-9_]*$'),
    connection_string varchar(1000) NOT NULL,
    object_name varchar(256) NOT NULL,
    title varchar(200) NOT NULL,
    description text NOT NULL,
    grain varchar(400) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    row_cap integer NOT NULL DEFAULT 500 CONSTRAINT ck_datasource_row_cap CHECK (row_cap BETWEEN 1 AND 2147483646),
    query_timeout_seconds integer NOT NULL DEFAULT 30 CONSTRAINT ck_datasource_query_timeout_seconds CHECK (query_timeout_seconds BETWEEN 1 AND 86400)
);
CREATE TABLE IF NOT EXISTS datagateway.datasourcecolumn (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datasource_fk integer NOT NULL REFERENCES datagateway.datasource(id),
    column_name varchar(128) NOT NULL CHECK (column_name COLLATE "C" ~ '^[A-Za-z_][A-Za-z0-9_]*$'),
    ordinal integer NOT NULL,
    title varchar(200) NOT NULL,
    description text NOT NULL,
    data_type varchar(10) NOT NULL CHECK (data_type IN ('text','number','date','bool')),
    unit varchar(50),
    magnitude varchar(10) CHECK (magnitude IN ('none','thousands','millions','billions')),
    display_format varchar(50),
    can_select boolean NOT NULL DEFAULT true,
    can_filter boolean NOT NULL DEFAULT false,
    can_sort boolean NOT NULL DEFAULT false,
    can_group boolean NOT NULL DEFAULT false,
    can_aggregate boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_datasource_name ON datagateway.datasource (lower(name COLLATE "C"));
CREATE UNIQUE INDEX IF NOT EXISTS uq_datasourcecolumn_name ON datagateway.datasourcecolumn (datasource_fk, lower(column_name COLLATE "C"));
CREATE TABLE IF NOT EXISTS datagateway.datasourceaudit (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_action char(1) NOT NULL CHECK (audit_action IN ('I','U','D')),
    audit_date timestamptz NOT NULL DEFAULT clock_timestamp(),
    audit_login varchar(128) NOT NULL DEFAULT session_user,
    datasource_fk integer NOT NULL,
    name varchar(128) NOT NULL,
    connection_string varchar(1000) NOT NULL,
    object_name varchar(256) NOT NULL,
    title varchar(200) NOT NULL,
    description text NOT NULL,
    grain varchar(400) NOT NULL,
    is_active boolean NOT NULL,
    row_cap integer,
    query_timeout_seconds integer
);
CREATE OR REPLACE FUNCTION datagateway.audit_datasource() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, datagateway, pg_temp
AS $audit$
DECLARE image datagateway.datasource%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN image := OLD; ELSE image := NEW; END IF;
    INSERT INTO datagateway.datasourceaudit
        (audit_action, audit_date, audit_login, datasource_fk, name, connection_string, object_name, title, description, grain, is_active, row_cap, query_timeout_seconds)
    VALUES (substr(TG_OP,1,1), clock_timestamp(), session_user,
        image.id, image.name, image.connection_string, image.object_name, image.title, image.description, image.grain, image.is_active, image.row_cap, image.query_timeout_seconds);
    RETURN NULL;
END
$audit$;
CREATE OR REPLACE TRIGGER tr_datasource_audit
AFTER INSERT OR UPDATE OR DELETE ON datagateway.datasource
FOR EACH ROW EXECUTE FUNCTION datagateway.audit_datasource();
REVOKE ALL ON FUNCTION datagateway.audit_datasource() FROM PUBLIC;
