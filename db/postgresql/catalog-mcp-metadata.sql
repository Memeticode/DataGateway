-- Existing catalog readers keep the same SELECT access on the new projection views.
DO $grants$
DECLARE reader record;
BEGIN
    FOR reader IN SELECT DISTINCT grantee
        FROM information_schema.table_privileges
        WHERE table_schema = 'datagateway' AND table_name = 'vdatasource'
          AND privilege_type = 'SELECT' AND grantee <> 'PUBLIC'
    LOOP
        EXECUTE format('GRANT SELECT ON datagateway.vmcpserver, datagateway.vmcptool TO %I', reader.grantee);
    END LOOP;
END
$grants$;
