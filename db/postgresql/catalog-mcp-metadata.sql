CREATE TABLE IF NOT EXISTS datagateway.mcpserver (
    id int PRIMARY KEY CHECK (id = 1),
    title varchar(80) NOT NULL CHECK ((char_length(title) + char_length(regexp_replace(title COLLATE "C", U&'[^\+010000-\+10FFFF]', '', 'g'))) BETWEEN 1 AND 80 AND btrim(title, U&'\0009\000A\000B\000C\000D\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000') COLLATE "C" <> '' AND strpos(title, chr(10)) = 0 AND strpos(title, chr(13)) = 0),
    about varchar(1000) NOT NULL CHECK ((char_length(about) + char_length(regexp_replace(about COLLATE "C", U&'[^\+010000-\+10FFFF]', '', 'g'))) BETWEEN 1 AND 1000 AND btrim(about, U&'\0009\000A\000B\000C\000D\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000') COLLATE "C" <> '')
);
CREATE TABLE IF NOT EXISTS datagateway.mcpserveraudit (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_action char(1) NOT NULL CHECK (audit_action IN ('I','U','D')),
    audit_date timestamptz NOT NULL DEFAULT clock_timestamp(),
    audit_login varchar(128) NOT NULL DEFAULT session_user,
    mcpserver_fk int NOT NULL,
    title varchar(80) NOT NULL,
    about varchar(1000) NOT NULL
);
CREATE OR REPLACE FUNCTION datagateway.audit_mcpserver() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, datagateway, pg_temp
AS $audit$
DECLARE image datagateway.mcpserver%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN image := OLD; ELSE image := NEW; END IF;
    INSERT INTO datagateway.mcpserveraudit (audit_action, audit_date, audit_login, mcpserver_fk, title, about)
    VALUES (substr(TG_OP,1,1), clock_timestamp(), session_user, image.id, image.title, image.about);
    RETURN NULL;
END
$audit$;
CREATE OR REPLACE TRIGGER tr_mcpserver_audit
AFTER INSERT OR UPDATE OR DELETE ON datagateway.mcpserver
FOR EACH ROW EXECUTE FUNCTION datagateway.audit_mcpserver();
REVOKE ALL ON FUNCTION datagateway.audit_mcpserver() FROM PUBLIC;
REVOKE ALL ON datagateway.mcpserver, datagateway.mcpserveraudit FROM PUBLIC;
